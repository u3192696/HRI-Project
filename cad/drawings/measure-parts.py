"""Automatic dimension inventory for the split part files.

For each .FCStd: find the Part container and its Bodies (the printable
sub-parts), and measure from the solid:
  - overall size, volume, solid count (solid count > 1 == unprintable part)
  - holes: cylindrical faces, classified concave (hole) vs convex (fillet/boss)
    by OCC face orientation AND by the radial-normal test, both must agree
  - per hole group: diameter, axis, count, through-vs-blind, pattern extents
  - fillet radii actually present in the solid
Every number is read from the BRep, never from the sketch text.

Run:  freecadcmd measure-parts.py
Out:  cad/drawings/DIMENSIONS.md + dimensions.csv
"""
import FreeCAD as App
import os, glob, collections, csv

D = "/home/danny/Projects/hri-project/cad/drawings"
ROUND = 2


def radial(fc):
    """(axis point, axis dir, point on face, outward radial unit vector)"""
    s = fc.Surface
    u0, u1, v0, v1 = fc.ParameterRange
    p = fc.valueAt((u0 + u1) / 2, (v0 + v1) / 2)
    ax = s.Axis
    bp = s.Center
    rad = App.Vector(p.x - bp.x, p.y - bp.y, p.z - bp.z)
    rad = rad - ax * rad.dot(ax)
    if rad.Length > 1e-9:
        rad.normalize()
    return bp, ax, p, rad


def classify(fc):
    """'hole' if the material is outside the cylinder, 'outer' otherwise.
    Two independent tests, both must agree."""
    s = fc.Surface
    bp, ax, p, rad = radial(fc)
    n = fc.normalAt(0.5, 0.5) if False else None
    u0, u1, v0, v1 = fc.ParameterRange
    n = fc.normalAt((u0 + u1) / 2, (v0 + v1) / 2)
    geo = "hole" if n.dot(rad) < 0 else "outer"
    occ = "hole" if fc.Orientation == "Reversed" else "outer"
    return geo if geo == occ else ("ambiguous:" + geo + "/" + occ)


def axial_len(fc):
    """axial extent of a cylindrical face (v parameter runs along the axis)"""
    u0, u1, v0, v1 = fc.ParameterRange
    a = fc.valueAt((u0 + u1) / 2, v0)
    b = fc.valueAt((u0 + u1) / 2, v1)
    return abs((b - a).Length)


def holes_of(shape):
    bb = shape.BoundBox
    extent = {"x": bb.XLength, "y": bb.YLength, "z": bb.ZLength}
    groups = collections.defaultdict(list)
    for fc in shape.Faces:
        if fc.Surface.TypeId != "Part::GeomCylinder":
            continue
        if classify(fc) != "hole":
            continue
        bp, ax, p, rad = radial(fc)
        key = (round(fc.Surface.Radius * 2, ROUND),
               tuple(round(getattr(ax, a), 0) for a in "xyz"))
        groups[key].append((bp, p, axial_len(fc)))
    out = []
    for (dia, ax), faces in sorted(groups.items()):
        # a hole is THROUGH when its cylindrical wall spans the full part
        # thickness along that axis (OCC gives a through hole ONE face, so
        # counting faces does not work)
        axis_letter = "xyz"[max(range(3), key=lambda i: abs(ax[i]))]
        thick = extent[axis_letter]
        span = max(f[2] for f in faces)
        thru = span >= 0.97 * thick
        out.append({"dia": dia, "axis": ax, "faces": len(faces),
                    "through": thru, "n": len(faces),
                    "axial": round(span, ROUND), "thick": round(thick, ROUND)})
    return out


def radii_of(shape):
    r = collections.Counter()
    for fc in shape.Faces:
        if fc.Surface.TypeId == "Part::GeomCylinder" and classify(fc) == "outer":
            r[round(fc.Surface.Radius, ROUND)] += 1
    return sorted(r.items())


rows = []
md = ["# Dimension inventory (measured from the BRep)", "",
      "Generated by `cad/drawings/measure-parts.py` via `freecadcmd`. Every value is",
      "read from the solid geometry, not from sketch text. `solids` must be 1 for a",
      "part to be printable as one piece.", ""]

for f in sorted(glob.glob(os.path.join(D, "*.FCStd"))):
    doc = App.openDocument(f)
    stem = os.path.basename(f)[:-6]
    part = next((o for o in doc.Objects if o.TypeId == "App::Part"), None)
    bodies = [o for o in doc.Objects if o.TypeId == "PartDesign::Body"]
    # only keep bodies that are children of the Part container (the real sub-parts)
    kids = []
    if part is not None:
        kids = [o for o in part.Group if o.TypeId == "PartDesign::Body"]
    if not kids:
        kids = bodies
    md.append("## %s  (%d body/ies in container)" % (stem, len(kids)))
    md.append("")
    md.append("| sub-part | size XxYxZ (mm) | volume (mm3) | solids | holes | fillets / bosses |")
    md.append("|---|---|---|---|---|---|")
    for b in kids:
        sh = b.Shape
        bb = sh.BoundBox
        hs = holes_of(sh)
        rr = radii_of(sh)
        htxt = "; ".join("%.2f dia along %s%s%s" % (
            h["dia"], "/".join("%g" % v for v in h["axis"]),
            " x%d" % h["n"] if h["n"] > 1 else "",
            " THRU" if h["through"] else " blind, %g deep in %g" % (h["axial"], h["thick"])) for h in hs) or "&mdash;"
        rtxt = ", ".join("R%g x%d" % (r, n) for r, n in rr) or "&mdash;"
        md.append("| %s | %.2f x %.2f x %.2f | %.0f | %d | %s | %s |" % (
            b.Name, bb.XLength, bb.YLength, bb.ZLength, sh.Volume, len(sh.Solids), htxt, rtxt))
        rows.append({"file": stem, "body": b.Name,
                     "X": round(bb.XLength, ROUND), "Y": round(bb.YLength, ROUND),
                     "Z": round(bb.ZLength, ROUND), "volume": round(sh.Volume),
                     "solids": len(sh.Solids),
                     "holes": " | ".join("%.2f/%s/%d%s" % (h["dia"], "/".join("%g" % v for v in h["axis"]),
                                                           h["n"], "THRU" if h["through"] else "blind") for h in hs),
                     "fillets": " ".join("R%g" % r for r, n in rr)})
    if part is not None:
        pbb = part.Shape.BoundBox
        md.append("| **assembled (Part)** | **%.2f x %.2f x %.2f** | %.0f | %d | | |" % (
            pbb.XLength, pbb.YLength, pbb.ZLength, part.Shape.Volume, len(part.Shape.Solids)))
        # tiling check: do the sub-part boxes add up to the assembled box?
        vols = sum(b.Shape.Volume for b in kids)
        delta = 100.0 * (vols - part.Shape.Volume) / max(part.Shape.Volume, 1)
        md.append("")
        md.append("  sum of sub-part volumes %.0f vs assembled %.0f (delta %+.1f%%)" % (
            vols, part.Shape.Volume, delta))
        if abs(delta) > 1.0:
            md.append("")
            md.append("  **WARNING: the Part container does not hold all sub-parts** "
                      "- an assembled view drawn from it would be wrong.")
            for b in kids:
                pl = b.Placement.Base
                md.append("  - %s at (%.2f, %.2f, %.2f), in Part group: %s, shape solids %d" % (
                    b.Name, pl.x, pl.y, pl.z, b.Name in [g.Name for g in part.Group],
                    len(b.Shape.Solids)))
        for b in kids:
            if len(b.Shape.Solids) > 1:
                md.append("")
                md.append("  **WARNING: %s is %d separate solids** - not printable as one piece "
                          "without splitting or a support decision." % (b.Name, len(b.Shape.Solids)))
    md.append("")
    App.closeDocument(doc.Name)

open(os.path.join(D, "DIMENSIONS.md"), "w").write("\n".join(md))
with open(os.path.join(D, "dimensions.csv"), "w", newline="") as fh:
    w = csv.DictWriter(fh, fieldnames=list(rows[0].keys()))
    w.writeheader()
    w.writerows(rows)
print("\n".join(md))
print("\nwrote DIMENSIONS.md and dimensions.csv (%d rows)" % len(rows))
